"""Assemble reports/RESULTS.md from every result JSON so no number in the report is typed by hand.

    python scripts/build_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "reports"


def load(rel: str) -> dict | None:
    p = ROOT / rel
    return json.loads(p.read_text()) if p.exists() else None


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f} %"


def f3(x):
    return "n/a" if x is None else f"{x:.3f}"


def main() -> None:
    out = ["# Results (auto-generated by scripts/build_report.py)\n"]

    # ---------------------------------------------------------------- detection
    det = load("reports/experiments/detection/detection_benchmark.json")
    if det:
        out += ["## 1. Person detection benchmark (COCO-classroom test: 104 images, 767 people)\n",
                "| model | mAP@0.5 | mAP@[.5:.95] | count MAE all / no-crowd images | recall small / medium / large | size-recall gap | latency ms (mean / p95) | mAP@0.5 low light / motion blur |",
                "|---|---|---|---|---|---|---|---|"]
        for n, r in det.items():
            rb = r["recall_by_size"]
            rob = r["robustness_mAP50"]
            out.append(f"| {n} | {f3(r['mAP50'])} | {f3(r['mAP50_95'])} | {r['count_MAE']:.2f} / {r.get('count_MAE_no_crowd', float('nan')):.2f} | "
                       f"{' / '.join(f3(v) for v in rb.values())} | {f3(r['size_recall_gap'])} | "
                       f"{r['latency_ms_mean']:.0f} / {r['latency_ms_p95']:.0f} | {f3(rob['low_light'])} / {f3(rob['motion_blur'])} (clean {f3(rob['clean'])}) |")
        n_nc = next(iter(det.values())).get("images_no_crowd")
        out.append(f"\n'no-crowd' = the {n_nc} test images without a COCO crowd region. On the others COCO labels at most "
                   "~13 people individually, so the ground-truth count is incomplete. Count threshold chosen on the validation split.\n")

    seat = load("reports/experiments/seating/seating.json")
    if seat:
        out += ["## 2. Segmentation (person pixels, COCO-classroom test)\n",
                "| method | person IoU | latency ms |", "|---|---|---|",
                f"| semantic: LR-ASPP MobileNetV3 | {f3(seat['semantic_LRASPP_person_IoU'])} | {seat['semantic_latency_ms']:.0f} |",
                f"| instance: YOLOv8n-seg (union of masks) | {f3(seat['instance_YOLOv8nSeg_person_IoU'])} | {seat['instance_latency_ms']:.0f} |",
                f"\nMean chairs detected per image: {seat['mean_chairs_detected']:.1f}\n"]

    # ---------------------------------------------------------------- engagement
    eng = load("reports/experiments/engagement/engagement.json")
    if eng:
        n_test = sum(eng["split_counts(engaged,neutral,disengaged)"]["test"])
        out += [f"## 3. Engagement (alertness) classification — leakage-safe test split ({n_test} frames)\n",
                "| model | accuracy | macro-F1 | per-class F1 (engaged / neutral / disengaged) | ms per crop |", "|---|---|---|---|---|"]
        for k in ["resnet18_linear_probe", "googlenet_linear_probe", "resnet18_finetuned"]:
            r = eng[k]
            ms = r.get("ms_per_crop", r.get("feature_ms_per_image"))
            out.append(f"| {k} | {f3(r['accuracy'])} | {f3(r['macro_f1'])} | {' / '.join(f3(v) for v in r['f1'])} | {ms:.0f} |")
        ci = eng["resnet18_finetuned"]["macro_f1_95CI"]
        out.append(f"\nFine-tuned ResNet-18 macro-F1 95 % bootstrap CI: [{ci[0]:.3f}, {ci[1]:.3f}]. "
                   f"Split sizes (engaged/neutral/disengaged): {eng['split_counts(engaged,neutral,disengaged)']}\n")

    cv = load("reports/experiments/engagement/engagement_cv.json")
    if cv:
        out += [f"**{cv['folds']}-fold grouped CV over time blocks (linear probes, {cv['frames']} frames)** — the estimate to trust, "
                "because a single test split of a few time blocks from one subject is high-variance:\n",
                "| backbone | macro-F1 mean ± std | per fold |", "|---|---|---|"]
        for k in ["resnet18", "googlenet"]:
            out.append(f"| {k} | {cv[k]['mean']:.3f} ± {cv[k]['std']:.3f} | {', '.join(f'{x:.2f}' for x in cv[k]['macro_f1_folds'])} |")
        out.append("")

    # ---------------------------------------------------------------- sequence
    tr = load("reports/experiments/sequence/trend_models.json")
    if tr:
        s, c = tr["student_level_real"], tr["class_level_simulated"]
        out += ["## 4. Temporal models\n", "**Student-level trend (real data, forecast mean engagement of next 12 frames from last 24):**\n",
                "| model | test MAE |", "|---|---|",
                f"| last value | {f3(s['last_value'])} |", f"| window mean | {f3(s['window_mean'])} |", f"| ridge (flattened) | {f3(s['ridge_flat'])} |"]
        for a in ["tanh", "sigmoid", "step"]:
            out.append(f"| LSTM ({a} cell) | {f3(s[f'lstm_{a}']['mean'])} ± {f3(s[f'lstm_{a}']['std'])} |")
        out.append(f"\nWindows: {s['n_windows']}\n")
        out += ["**Class-level trend (SIMULATED lectures, 5-min horizon):** "
                f"LSTM MAE {f3(c['lstm_MAE'])} vs persistence {f3(c['persistence_MAE'])} vs 3-min moving average {f3(c['moving_avg3_MAE'])}\n"]
    ag = load("reports/experiments/sequence/transformer_aggregator.json")
    if ag:
        out += ["**Transformer feature aggregator (SIMULATED frames, real classifier errors):**\n",
                "| aggregator | engaged-fraction MAE |", "|---|---|",
                f"| mean of hard labels | {f3(ag['mean_hard_label_MAE'])} |", f"| mean of probabilities | {f3(ag['mean_prob_MAE'])} |",
                f"| DeepSets | {f3(ag['deepsets_MAE'])} |", f"| Transformer (CLS attention) | {f3(ag['transformer_MAE'])} |",
                f"\nCorrelation of CLS attention with face size: {f3(ag['attention_vs_face_size_corr'])}\n"]
    lat = load("reports/experiments/sequence/latent_space.json")
    if lat:
        out.append(f"**Latent space:** silhouette by engagement class — supervised ResNet-18 embedding {f3(lat['silhouette_cnn_embedding'])}, "
                   f"unsupervised VAE latent {f3(lat['silhouette_vae_latent'])}.\n")

    # ---------------------------------------------------------------- face
    fr = load("reports/eval/face_recognition.json")
    if fr:
        v, ss = fr["verification"], fr["sessions"]
        out += ["## 5. Face-recognition attendance (LFW, threshold %.3f)\n" % fr["threshold"],
                f"Face detection rate: {pct(fr['detection_rate'], 2)} of {fr['images']} images.\n",
                f"**Verification** ({v['genuine_pairs']} genuine / {v['impostor_pairs']} impostor pairs): FAR {pct(v['FAR'], 3)}, FRR {pct(v['FRR'], 2)}; "
                + ", ".join(f"TAR@FAR={k.split('=')[1]}: {pct(v[k]['TAR'])}" for k in v if k.startswith("TAR@")) + "\n",
                f"**Simulated class sessions** ({ss['sessions']} sessions × {ss['class_size']} students, 5 absent, 3 strangers, 2 frames): "
                f"attendance recall {pct(ss['attendance_recall'], 2)}, false-present rate {pct(ss['false_present_rate'], 2)}, count MAE {ss['count_MAE']:.2f}\n",
                "**Fairness (groups from predicted LFW attributes):**\n", "| attribute | group | n | attendance recall | FRR | FAR |", "|---|---|---|---|---|---|"]
        for attr in ["gender", "ethnicity"]:
            gv = fr["group_verification"][attr]["by_group"]
            for g, r in ss[f"recall_by_{attr}"].items():
                vg = gv.get(g, {})
                out.append(f"| {attr} | {g} | {r['n']} | {pct(r['recall'], 2)} | {pct(vg.get('FRR'), 2)} | {pct(vg.get('FAR'), 3)} |")
            out.append(f"| {attr} | **gap** | | {pct(ss[f'recall_gap_{attr}']['gap'], 2)} | {pct(fr['group_verification'][attr]['FRR_gap'], 2)} | {pct(fr['group_verification'][attr]['FAR_gap'], 3)} |")
        out += ["", "**Robustness** (clean enrolment, degraded probes; rank-1 identification above threshold):\n",
                "| condition | face detected | correctly identified |", "|---|---|---|"]
        for k, r in fr["robustness"].items():
            out.append(f"| {k} | {pct(r['face_detected'])} | {pct(r['rank1_identified'])} |")
        out.append("")

    # ---------------------------------------------------------------- product
    pl = load("reports/eval/pipeline_latency.json")
    if pl:
        out += ["## 6. Integrated product latency (CPU, Intel i3-1215U, 40 classroom test images)\n",
                "| stage | mean ms | p95 ms |", "|---|---|---|"]
        for k in ["detect", "faces", "engagement", "seating", "total"]:
            out.append(f"| {k} | {pl[k]['mean']:.0f} | {pl[k]['p95']:.0f} |")
        out.append(f"\nPeak resident memory: {pl['peak_rss_mb']:.0f} MB. Measured on battery power with Windows capping the CPU "
                   "at 1.2 GHz (worst case; the detector benchmark in section 1 ran on mains power). p95 is driven by frames "
                   "with many faces, because identity and engagement run once per face. Re-measure with "
                   "`python -m smartattend stage pipeline_latency`.\n")
    dm = load("reports/demo/session_summary.json")
    if dm:
        chk = dm["demo_check"]
        out += ["## 7. End-to-end demo (synthetic classroom of 12 LFW identities, 2 absent, 1 stranger)\n",
                f"Register correct for {chk['correct_register_entries']} / {chk['of']} students; flagged for teacher review: "
                f"{', '.join(chk.get('flagged_for_review', [])) or 'none'}; stranger marked as a student: {chk['stranger_marked_as_someone']}. "
                f"Mean latency {dm['mean_latency_ms']:.0f} ms/frame (13 faces per frame, battery power), mean class engagement "
                f"{dm['mean_class_engagement']:.2f}. Video: reports/demo/annotated.mp4\n",
                "Before the min-fraction rule, the absent student Dennis_Kucinich was marked present: the non-enrolled "
                "stranger was matched to him in 7 of 20 frames (best similarity 0.451). With the rule he is flagged for review instead.\n"]

    # ---------------------------------------------------------------- fundamentals
    oc = load("reports/experiments/nnfund/optimizer_comparison.json")
    if oc:
        out += ["## 8. NumPy fundamentals (synthetic engagement features)\n", "| optimizer | final train loss | val acc |", "|---|---|---|"]
        out += [f"| {k} | {v['final_train_loss']:.4f} | {f3(v['final_val_acc'])} |" for k, v in oc.items()]
        out.append("")
    ov = load("reports/experiments/nnfund/overfitting.json")
    if ov:
        out += ["| overfitting study (60 samples, 128-128 MLP) | train acc | val acc | early-stop epoch |", "|---|---|---|---|"]
        out += [f"| {k} | {f3(v['train_acc'])} | {f3(v['val_acc'])} | {v['early_stop_epoch']} |" for k, v in ov.items()]
        out.append("")

    # ---------------------------------------------------------------- real classroom video (Requirements 7-10)
    ce = load("reports/eval/classroom_eval.json")
    bm = load("reports/eval/benchmark.json")
    if bm:
        c = bm["proposal_recall_ceiling"]
        out += ["## 9. Detector benchmark on real classroom video (Kaggle test classroom: 85 frames, 1,159 students)\n",
                "R-CNN and Fast R-CNN are implemented in `src/smartattend/vision/rcnn.py`. 'Kaggle' = trained or fine-tuned on the "
                "Kaggle training classrooms. Thresholds chosen on validation. Time = median with all models run in turn on the "
                "same frames (laptop CPU on battery); R-CNN and Fast R-CNN additionally need 1.56 s of selective search per frame.\n",
                "| model | Kaggle | mAP@0.5 | mAP@[.5:.95] | recall | count MAE | ms per frame | parameters (M) |", "|---|---|---|---|---|---|---|---|"]
        for n, r in bm["detectors"].items():
            out.append(f"| {n} | {'yes' if r['trained_on_kaggle'] else 'no'} | {f3(r['mAP50'])} | {f3(r['mAP50_95'])} | "
                       f"{f3(r['recall50_at_threshold'])} | {r['count_mae']:.2f} | {r['ms_per_image_median']:.0f} | {r['params_M']:.1f} |")
        out.append(f"\nSelective-search proposals cover {pct(c['iou0.5'])} of students at IoU 0.5 and {pct(c['iou0.7'])} at IoU 0.7: "
                   "the ceiling for R-CNN and Fast R-CNN.\n")
    if ce:
        r = ce["states_face_rule"]
        out += ["## 10. Attentive / distracted / inactive per student (Kaggle test classroom)\n",
                "| model | accuracy | macro-F1 [95% CI] | F1 attentive / distracted / inactive | ms per crop |", "|---|---|---|---|---|"]
        for a, c in ce["states_cnn"].items():
            out.append(f"| {a} fine-tuned | {f3(c['test']['accuracy'])} | {f3(c['test']['macro_f1'])} [{f3(c['macro_f1_95CI'][0])}-"
                       f"{f3(c['macro_f1_95CI'][1])}] | {' / '.join(f'{v:.2f}' for v in c['test']['f1'])} | {c['ms_per_crop']:.0f} |")
        out.append(f"| app face rule (judges {pct(r['judged_fraction'], 0)} of students) | {f3(r['judged']['accuracy'])} | "
                   f"{f3(r['judged']['macro_f1'])} on judged; {f3(r['all_students_unjudged_as_attentive']['macro_f1'])} on all | "
                   f"{' / '.join(f'{v:.2f}' for v in r['judged']['f1'])} | - |")
        t = ce["trend"]
        out.append(f"\nTrend over the test video ({t['detector']} + {t['state_model']}): labelled mean attentive share "
                   f"{t['true_mean_attentive']:.2f}, predicted {t['pred_mean_attentive']:.2f}, correlation {t['attentive_share_corr']:.2f}.\n")
    sq = load("reports/eval/sequence_models.json")
    if sq:
        def fmt(v):
            if isinstance(v["mae"], list):
                return f"{v['mae'][0]:.3f} ± {v['mae'][1]:.3f} | {v['corr'][0]:+.2f} ± {v['corr'][1]:.2f}"
            return f"{v['mae']:.3f} | {v['corr']:+.2f}"

        out += ["## 11. Sequence models on real classroom video (attentive share from the last 8 frames)\n",
                f"Trained on {sq['windows']['train']} windows from 3 videos, tested on {sq['windows']['test']} frames of the test classroom, 5 seeds.\n",
                "| model | MAE | correlation with the labelled trend |", "|---|---|---|"]
        out += [f"| {k} | {fmt(v)} |" for k, v in sq["temporal"].items()]
        lv = sq["leave_one_video_out"]["mean_mae"]
        out.append("\nLeave-one-video-out MAE on the training classroom: " + ", ".join(f"{k} {v:.3f}" for k, v in lv.items())
                   + ". The learned sequence models do not beat the per-frame output: three training videos are too few.\n")
    fe = load("reports/eval/final_evaluation.json")
    if fe:
        out += ["## 12. Final evaluation of the classroom pipeline (fine-tuned YOLOv8n -> ResNet18), Kaggle test classroom\n",
                "**Robustness (same frames, degraded)**\n", "| condition | mAP@0.5 | count MAE | state macro-F1 |", "|---|---|---|---|"]
        out += [f"| {k} | {f3(v['mAP50'])} | {v['count_mae']:.2f} | {f3(v['state_macro_f1'])} |" for k, v in fe["robustness"].items()]
        fa, er, la = fe["fairness"], fe["errors"], fe["latency"]
        out += ["", "**Fairness (who is served worse)**\n", "| group | found by the detector | state classified correctly |", "|---|---|---|"]
        out += [f"| {k} | {f3(v)} | {f3(fa['state_by_size'][k]['accuracy'])} |" for k, v in fa["detection_recall_by_size"].items()]
        out.append(f"\nGap small vs large: detection {f3(fa['detection_recall_gap_size'])}, state accuracy {f3(fa['state_accuracy_gap_size'])}. "
                   "Found by true state: " + ", ".join(f"{k} {f3(v)}" for k, v in fa["detection_recall_by_true_state"].items()) + ".\n")
        on_battery = (la["machine"].get("battery") or {}).get("plugged_in") is False
        out += ["**Error analysis**\n",
                f"Missed at IoU 0.5: {er['missed']} of {er['students']} students (" + ", ".join(f"{k} {v}" for k, v in er["missed_by_size"].items())
                + "). False boxes: " + ", ".join(f"{k} {v}" for k, v in er["false_boxes"].items())
                + ". Largest state confusions: " + "; ".join(f"{d['true']} -> {d['predicted']} {d['n']} ({pct(d['share_of_true'], 0)})"
                                                            for d in er["largest_state_confusions"]) + ".\n",
                "**Latency (laptop CPU" + (", on battery: worst case" if on_battery else "") + ")**\n",
                "| pipeline | median ms | p95 ms |", "|---|---|---|",
                f"| classroom pipeline (detect + states) | {la['classroom_pipeline']['total']['median']:.0f} | {la['classroom_pipeline']['total']['p95']:.0f} |"]
        out += [f"| {k.replace('full_app_', 'full app with faces, ')} | {v['total']['median']:.0f} | {v['total']['p95']:.0f} |"
                for k, v in la.items() if k.startswith("full_app_")]
        out.append("")
    acc = load("reports/eval/acceptance.json")
    if acc:
        def fm(v):
            return "-" if v is None else (f"{v:.3f}" if abs(v) < 10 else f"{v:.0f}")

        out += ["## 13. Acceptance scorecard (`python -m smartattend acceptance`)\n",
                "| id | stakeholder | metric | target | measured | status |", "|---|---|---|---|---|---|"]
        out += [f"| {r['id']} | {r['stakeholder']} | {r['metric']} | {r['target']} | {fm(r['measured'])} | **{r['status']}** |" for r in acc]
        n_pass = sum(r["status"] == "PASS" for r in acc)
        out.append(f"\n{n_pass} of {len(acc)} requirements pass.\n")

    (R / "RESULTS.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {R / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
